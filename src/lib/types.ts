// ---------------------------------------------------------------------------
// Mushaf
// ---------------------------------------------------------------------------
export type MushafCode = "v2" | "indopak";

export const MUSHAF_CODES: MushafCode[] = ["v2", "indopak"];

/** Codes that use per-page QCF glyph fonts (not Unicode text) */
export const QCF_CODES: MushafCode[] = ["v2"];

/** Codes that use a single shared Unicode font */
export const UNICODE_FONT_CODES: MushafCode[] = ["indopak"];

export const MUSHAF_DISPLAY_NAMES: Record<MushafCode, string> = {
  v2: "Madina (V2)",
  indopak: "Indopak",
};

export const MUSHAF_LINES: Record<MushafCode, number> = {
  v2: 15,
  indopak: 15,
};

// ---------------------------------------------------------------------------
// Mushaf page data (matches the JSON generated by scripts/generate-mushaf-assets.ts)
// ---------------------------------------------------------------------------
export interface MushafWord {
  text: string;
  verseKey: string;
  x: number;
  width: number;
  charTypeName: string;
}

export interface MushafLine {
  lineNumber: number;
  words: MushafWord[];
}

export interface MushafPagePayload {
  page: number;
  mushafCode: string;
  lines: MushafLine[];
}

// ---------------------------------------------------------------------------
// Chapter metadata (from /chapters API)
// ---------------------------------------------------------------------------
export interface Chapter {
  id: number;
  nameSimple: string;
  nameArabic: string;
  versesCount: number;
  pages: [number, number]; // [startPage, endPage] in Madani mushaf
  revelationPlace: "makkah" | "madinah";
  bismillahPre: boolean;
}

