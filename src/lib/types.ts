// ---------------------------------------------------------------------------
// Reading mode
// ---------------------------------------------------------------------------
export type ReadingMode = "swipe" | "scroll";

// ---------------------------------------------------------------------------
// User preferences (persisted to localStorage)
// ---------------------------------------------------------------------------
